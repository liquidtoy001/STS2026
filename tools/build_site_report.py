"""Turn finished run folders into a documentation-site report and small Git records.

For each experiment this writes:
  docs/site/reports/<id>.data.js      trimmed metrics for docs/site/report.html#<id>
  docs/records/<id>/<arm>/            run_config, status, evaluation history, manifest, log
Checkpoints, audio and full training histories stay out of Git (team Google Drive).
The hand-written narrative lives in docs/site/reports/<id>.notes.js and is never overwritten.

Example:
  python tools/build_site_report.py --id full-train-gan --reference gan0 \
    --run gan0=output/full-train/runs/full_gan0_20260929T175436031732Z \
    --run gan1=output/full-train/runs/full_gan1_20260929T170528763415Z \
    --log gan0=output/full-train/logs/vits-full-train-gan0.log \
    --log gan1=output/full-train/logs/vits-full-train-gan1.log
"""

import argparse
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TRAIN_FIELDS = ("step", "total", "mel", "stft", "duration", "kl", "wave", "gan", "gan_discriminator",
                "discriminator_real_score", "discriminator_fake_score", "sec_per_iter")
CONFIG_FIELDS = ("variant", "data_dir", "training_clips", "train_seed", "batch_size", "total_steps", "eval_every",
                 "loss_weights", "parameters", "gpu", "torch", "metadata_sha256", "notebook_sha256",
                 "eval_source_sha256", "scope", "resumed_from")


def pairs(values):
    result = {}
    for value in values or []:
        key, _, path = value.partition("=")
        if not path:
            raise SystemExit(f"Expected arm=path, got {value!r}")
        result[key] = Path(path)
    return result


def load(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def rounded(value):
    return None if value is None else float(f"{value:.5g}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--id", required=True, help="Report id, used in report.html#<id>")
    parser.add_argument("--run", action="append", required=True, help="arm=run_folder (repeat)")
    parser.add_argument("--reference", required=True, help="Arm that the others are compared against")
    parser.add_argument("--log", action="append", help="arm=kaggle_log (optional, repeat)")
    args = parser.parse_args()
    runs, logs = pairs(args.run), pairs(args.log)
    if args.reference not in runs:
        raise SystemExit("--reference must be one of the --run arms")

    report = {"id": args.id, "reference": args.reference, "arms": {}}
    records = ROOT / "docs" / "records" / args.id
    for arm, run in runs.items():
        run = (ROOT / run).resolve() if not run.is_absolute() else run
        status = load(run / "status.json")
        if status.get("status") != "completed":
            raise SystemExit(f"{arm}: status is {status.get('status')!r}; only completed runs are reported")
        config = load(run / "run_config.json")
        history = load(run / "training_history.json")
        report["arms"][arm] = {
            "run": run.name,
            "status": status,
            "config": {k: config.get(k) for k in CONFIG_FIELDS},
            "batch_sha256": load(run / "evaluation" / "manifest.json")["batch_sha256"],
            "eval": [{k: (rounded(v) if isinstance(v, float) else v) for k, v in row.items()}
                     for row in load(run / "evaluation" / "evaluation_history.json")],
            "train": {field: [rounded(row.get(field)) for row in history] for field in TRAIN_FIELDS},
            "per_sample_final": [{k: (rounded(v) if isinstance(v, float) else v) for k, v in row.items()}
                                 for row in load(sorted((run / "evaluation").glob("step_*/per_sample.json"))[-1])],
            # Checkpoints are kept next to the run tree: <root>/checkpoints/full-train/<run>/ (see docs/FULL_TRAINING.md).
            "checkpoints": sorted((p.name for p in (run.parents[3] / "checkpoints" / "full-train" / run.name).glob("*.pt")),
                                  key=lambda n: int(n.rsplit("_", 1)[1].split(".")[0])),
        }
        target = records / arm
        target.mkdir(parents=True, exist_ok=True)
        for name in ("run_config.json", "status.json"):
            shutil.copy2(run / name, target / name)
        for name in ("evaluation_history.json", "manifest.json"):
            shutil.copy2(run / "evaluation" / name, target / name)
        if arm in logs:
            shutil.copy2(logs[arm], target / "kaggle.log")

    out = ROOT / "docs" / "site" / "reports" / f"{args.id}.data.js"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("/* Generated by tools/build_site_report.py. Do not edit; rebuild instead. */\n"
                   "(window.STS_REPORTS = window.STS_REPORTS || {})[" + json.dumps(args.id) + "] = "
                   + json.dumps(report, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(out, f"{out.stat().st_size // 1024} KB")
    print(records)


if __name__ == "__main__":
    main()
