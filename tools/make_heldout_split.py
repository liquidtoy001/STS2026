"""Write the fixed TTS_0.10 held-out split: 100 LJSpeech clips never used for training.

Candidates are clips whose normalized transcription has 1-100 characters (the TTS_0.10
training filter), excluding the eight fixed probe clips LJ001-0001...0008. 100 IDs are drawn
with numpy.random.default_rng(2026) and stored sorted. Re-running on the same metadata.csv
reproduces the file exactly; never regenerate it once runs have started.

python tools/make_heldout_split.py --metadata data/LJSpeech-1.1/metadata.csv
"""

import argparse
import csv
import hashlib
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "sts_eval" / "splits" / "ljspeech_heldout_100.txt"
SEED = 2026
SIZE = 100
MAX_CHARS = 100
PROBE_IDS = {f"LJ001-{i:04d}" for i in range(1, 9)}


def read_metadata(path):
    with open(path, encoding="utf-8", newline="") as handle:
        return [row for row in csv.reader(handle, delimiter="|", quoting=csv.QUOTE_NONE)]


def build(metadata_path):
    rows = read_metadata(metadata_path)
    if len(rows) != 13100 or any(len(row) != 3 for row in rows):
        raise ValueError("Expected the complete LJSpeech-1.1 metadata.csv (13,100 rows, 3 fields).")
    candidates = sorted(row[0] for row in rows
                        if 1 <= len(row[2]) <= MAX_CHARS and row[0] not in PROBE_IDS)
    chosen = sorted(np.random.default_rng(SEED).choice(candidates, size=SIZE, replace=False).tolist())
    digest = hashlib.sha256(Path(metadata_path).read_bytes()).hexdigest()
    header = [
        "# TTS_0.10 held-out split: never used for training in any TTS_0.10 arm.",
        f"# Source: LJSpeech-1.1 metadata.csv sha256 {digest}",
        f"# Rule: normalized text 1-{MAX_CHARS} chars (csv.QUOTE_NONE), excluding LJ001-0001...0008;",
        f"#       {SIZE} of {len(candidates)} candidates, numpy.random.default_rng({SEED}).choice, sorted.",
        "# Generated by tools/make_heldout_split.py. Do not edit or regenerate after runs start.",
    ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(header + chosen) + "\n", encoding="utf-8", newline="\n")
    return OUTPUT, chosen


def load(path=OUTPUT):
    """Return the held-out IDs, ignoring comment lines."""
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    return [line.strip() for line in lines if line.strip() and not line.startswith("#")]


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--metadata", default=str(ROOT / "data" / "LJSpeech-1.1" / "metadata.csv"))
    output, chosen = build(parser.parse_args().metadata)
    print(output, len(chosen))
